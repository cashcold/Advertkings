// Shuffles an array randomly using Fisher-Yates
function shuffle<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// Generate full slate of random match-ups pairing ALL teams in the league
export function generateRandomRoundFixtures(
  leagueKey: LeagueKey,
  roundNumber: number
): FootballFixture[] {
  const teams = LEAGUE_TEAMS_MAP[leagueKey] || ENGLAND_TEAMS;
  const shuffled = shuffle(teams);
  const fixtures: FootballFixture[] = [];

  // Pair teams: 0 vs 1, 2 vs 3, ..., up to total teams (20 -> 10 matches, 18 -> 9 matches)
  for (let i = 0; i < shuffled.length - 1; i += 2) {
    const home = shuffled[i];
    const away = shuffled[i + 1];

    // Strength difference calculation
    // Home team gets a standard +0.25 strength bump
    const diff = home.stars + 0.25 - away.stars;

    // Realistic base odds calculation
    let rawHome = 2.45 - diff * 0.7 + (Math.random() - 0.5) * 0.2;
    let rawAway = 2.65 + diff * 0.75 + (Math.random() - 0.5) * 0.2;
    let rawDraw = 3.35 + Math.abs(diff) * 0.3 + (Math.random() - 0.5) * 0.25;

    // Clamp within realistic bookmaker range
    const homeOdds = Math.max(1.22, Math.min(8.5, Number(rawHome.toFixed(2))));
    const awayOdds = Math.max(1.25, Math.min(8.8, Number(rawAway.toFixed(2))));
    const drawOdds = Math.max(3.05, Math.min(5.2, Number(rawDraw.toFixed(2))));

    // 1X2 - 1UP (early payout if 1 up)
    const odds1UP = {
      home: Math.max(1.1, Number((homeOdds * 0.67).toFixed(2))),
      draw: drawOdds,
      away: Math.max(1.1, Number((awayOdds * 0.67).toFixed(2))),
    };

    // 1X2 - 2UP (early payout if 2 up)
    const odds2UP = {
      home: Math.max(1.05, Number((homeOdds * 0.55).toFixed(2))),
      draw: Math.max(3.4, Number((drawOdds * 1.08).toFixed(2))),
      away: Math.max(1.05, Number((awayOdds * 0.55).toFixed(2))),
    };

    // Expected goals for over/under ladders
    const avgStars = (home.stars + away.stars) / 2;
    const expGoals = 2.4 + (avgStars - 3.5) * 0.35;

    const overUnder = [
      {
        line: 0.5,
        over: 1.02,
        under: Number((13.5 + (Math.random() - 0.5) * 2).toFixed(2)),
      },
      {
        line: 1.5,
        over: Number((1.12 + Math.max(0, 3 - expGoals) * 0.08).toFixed(2)),
        under: Number((5.2 - Math.max(0, 3 - expGoals) * 0.8).toFixed(2)),
      },
      {
        line: 2.5,
        over: Number((1.48 + (3 - expGoals) * 0.22 + (Math.random() - 0.5) * 0.1).toFixed(2)),
        under: Number((2.55 - (3 - expGoals) * 0.22 + (Math.random() - 0.5) * 0.1).toFixed(2)),
      },
      {
        line: 3.5,
        over: Number((2.2 + (3 - expGoals) * 0.35 + (Math.random() - 0.5) * 0.15).toFixed(2)),
        under: Number((1.65 - (3 - expGoals) * 0.18 + (Math.random() - 0.5) * 0.1).toFixed(2)),
      },
      {
        line: 4.5,
        over: Number((3.8 + (3 - expGoals) * 0.5 + (Math.random() - 0.5) * 0.3).toFixed(2)),
        under: Number((1.26 - (3 - expGoals) * 0.05).toFixed(2)),
      },
    ];

    const bttsYes = Number((1.68 + (Math.random() - 0.5) * 0.26).toFixed(2));
    const bttsNo = Number((2.08 - (bttsYes - 1.68)).toFixed(2));

    fixtures.push({
      id: `${leagueKey}-r${roundNumber}-m${i / 2 + 1}`,
      homeTeam: home.name,
      homeAbbr: home.abbr,
      homeStars: Math.round(home.stars),
      homeColor: home.color,
      homeBg: home.bg,
      awayTeam: away.name,
      awayAbbr: away.abbr,
      awayStars: Math.round(away.stars),
      awayColor: away.color,
      awayBg: away.bg,
      league: leagueKey,
      moreCount: 71,
      odds1X2: { home: homeOdds, draw: drawOdds, away: awayOdds },
      odds1UP,
      odds2UP,
      overUnder,
      btts: { yes: bttsYes, no: bttsNo },
    });
  }

  return fixtures;
}

// Generates initial multi-league round fixtures
export function generateAllLeaguesFixtures(roundNumber: number): FootballFixture[] {
  const leagues: LeagueKey[] = ['england', 'spain', 'germany', 'france'];
  let all: FootballFixture[] = [];
  leagues.forEach((lg) => {
    all = all.concat(generateRandomRoundFixtures(lg, roundNumber));
  });
  return all;
}
